export const DEFAULT_SCHEMAS = RAW_SCHEMAS.map((schema) => {
  const perms = GRANTS[schema.id];
  if (!perms) return schema;
  const holders = DEFAULT_ROLES.filter((r) => r.permissions.some((x) => perms.includes(x))).map((r) => r.id);
  return {
    ...schema,
    fields: schema.fields.map((f) =>
      f.editableBy.length === 0 || (LOCKED[schema.id] || []).includes(f.key)
        ? f
        : { ...f, editableBy: [...new Set([...f.editableBy, ...holders])], ...(schema.id === COLLECTIONS.USERS ? { viewableBy: [...new Set([...f.viewableBy, ...holders])] } : {}) }
    ),
  };
});
