package com.communityos.amenities;

import com.communityos.adapter.persistence.InMemoryDocumentRepository;
import com.communityos.port.DocumentRepository;
import com.communityos.security.Constants;
import com.communityos.service.audit.AuditTrail;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ObjectNode;
import java.io.InputStream;
import java.time.Clock;
import java.time.Instant;
import java.time.ZoneOffset;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.Iterator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.zip.GZIPInputStream;

/**
 * Replays what the real JavaScript (src/lib/amenityServer.js) queued and changed for ~12,000 amenity messages, booking postings, reports and scheduler
 * passes (generated by backend/contract-server/test/gen-amenity-notify-golden.mjs, `npm run gen:amenity-notify`, in the India time zone), and reports every
 * place the Java gives a different answer: the rows it queued (in order), the rows it changed, what it returned.
 */
public final class AmenityNotifyConformanceCheck {
    private static final List<String> TRACK = List.of("ledger", "unitCredits", "notificationOutbox", "notifications", "notificationTemplates", "amenitySettings", "amenities");
    private final ObjectMapper json = new ObjectMapper();
    private final List<String> problems = new ArrayList<>();
    private final Map<String, Integer> seen = new LinkedHashMap<>();
    private int ops;

    public static void main(String[] args) throws Exception {
        AmenityNotifyConformanceCheck c = new AmenityNotifyConformanceCheck();
        c.run();
        System.out.println("operations=" + c.ops + " mismatches=" + c.problems.size() + " " + c.seen);
        c.problems.stream().limit(args.length > 0 ? Integer.parseInt(args[0]) : 8).forEach(System.out::println);
        System.exit(c.problems.isEmpty() ? 0 : 1);
    }

    List<String> problems() { return problems; }
    int ops() { return ops; }
    Map<String, Integer> seen() { return seen; }
    private void count(String k, int n) { seen.merge(k, n, Integer::sum); }

    void run() throws Exception {
        JsonNode gold;
        try (InputStream in = AmenityNotifyConformanceCheck.class.getResourceAsStream("/amenity-notify/golden.json.gz")) {
            if (in == null) throw new IllegalStateException("amenity-notify/golden.json.gz is missing: run `npm run gen:amenity-notify` in backend/contract-server");
            gold = json.readTree(new GZIPInputStream(in));
        }
        Constants constants = Constants.load(json);
        for (JsonNode c : gold.get("cases")) {
            Clock clock = Clock.fixed(Instant.parse(c.get("now").asText()), ZoneOffset.UTC);
            JsonNode world = c.get("world");
            for (JsonNode op : c.get("ops")) {
                ops++;
                DocumentRepository repo = new InMemoryDocumentRepository();
                world.fields().forEachRemaining(e -> e.getValue().forEach(r -> repo.upsert("t", e.getKey(), r.get("id").asText(), r)));
                Map<String, Map<String, String>> before = snapshot(repo);
                AmenitySystem system = new AmenitySystem(repo, new AuditTrail(repo, json, clock), clock, constants);
                AmenityNotifier notifier = new AmenityNotifier(repo, system, json);
                JsonNode settings = world.get("amenitySettings").size() > 0 ? world.get("amenitySettings").get(0) : json.createObjectNode();
                JsonNode want = op.get("expected");
                String kind = op.get("kind").asText();
                Map<String, Object> got = new LinkedHashMap<>();
                try {
                    switch (kind) {
                        case "notify" -> {
                            Map<String, String> extra = new HashMap<>();
                            op.get("extra").fields().forEachRemaining(e -> extra.put(e.getKey(), e.getValue().asText()));
                            notifier.notify("t", op.get("event").asText(), op.get("booking"), settings, op.get("reason").asText(), extra);
                            count("notify", 1);
                        }
                        case "post" -> { new AmenityPosting(repo, new AuditTrail(repo, json, clock), json, clock, constants, notifier).postWrite("t", op.get("next"), op.get("action").asText()); count("post", 1); }
                        case "report" -> {
                            AmenityNotifier.Sent s = notifier.sendReport("t", op.get("reportKind").asText(), op.get("from").isNull() ? null : op.get("from").asText(), op.get("to").isNull() ? null : op.get("to").asText(), AmenityConformanceCheck.ZONE);
                            ObjectNode ret = json.createObjectNode();
                            ret.put("subject", s.report().subject()); ret.put("text", s.report().text()); ret.put("queued", s.queued());
                            ObjectNode range = ret.putObject("range"); range.put("from", s.from()); range.put("to", s.to());
                            ObjectNode counts = ret.putObject("counts"); counts.put("pending", s.report().counts().pending()); counts.put("refundDue", s.report().counts().refundDue()); counts.put("held", s.report().counts().held());
                            AmenityReports.Money m = s.report().money();
                            ObjectNode money = ret.putObject("money");
                            money.put("depositsReturned", m.depositsReturned()); money.put("waived", m.waived()); money.put("waivedCount", m.waivedCount()); money.put("bookingsPaid", m.bookingsPaid()); money.put("taxable", m.taxable());
                            money.put("gst", m.gst()); money.put("fees", m.fees()); money.put("deposits", m.deposits()); money.put("collected", m.collected()); money.put("refunds", m.refunds()); money.put("retained", m.retained()); money.put("net", m.net());
                            got.put("ret", ret);
                            count("report", 1); count("reportQueued", s.queued());
                        }
                        case "run" -> {
                            AmenityScheduler.Stats s = new AmenityScheduler(repo, notifier, system, json, null).run("t", AmenityConformanceCheck.ZONE);
                            ObjectNode ret = json.createObjectNode();
                            ret.put("released", s.released()); ret.put("completed", s.completed()); ret.put("reminders", s.reminders()); ret.put("daily", s.daily()); ret.put("summary", s.summary());
                            got.put("ret", ret);
                            count("run", 1); count("released", s.released()); count("completed", s.completed()); count("reminders", s.reminders()); count("dailyReports", s.daily() ? 1 : 0); count("summaryReports", s.summary() ? 1 : 0);
                        }
                        default -> throw new IllegalStateException(kind);
                    }
                } catch (RuntimeException e) {
                    if (problems.isEmpty()) e.printStackTrace();
                    add(kind, op, "CRASH " + e);
                    continue;
                }
                String diff = compare(want, got, before, repo);
                if (diff != null) add(kind, op, diff);
                else for (String coll : TRACK) count("rows:" + coll, want.get("created").get(coll).size());
            }
        }
    }

    private void add(String kind, JsonNode op, String diff) {
        if (problems.size() < 300) problems.add(kind + " " + (op.has("event") ? op.get("event").asText() : op.has("action") ? op.get("action").asText() : op.has("reportKind") ? op.get("reportKind").asText() : "")
                + "\n" + diff + "\n   op=" + abbreviate(op.toString()));
    }
    private static String abbreviate(String s) { return s.length() > 900 ? s.substring(0, 900) + "..." : s; }

    private Map<String, Map<String, String>> snapshot(DocumentRepository repo) {
        Map<String, Map<String, String>> out = new HashMap<>();
        for (String c : TRACK) { Map<String, String> m = new LinkedHashMap<>(); for (JsonNode r : repo.list("t", c)) m.put(r.get("id").asText(), AmenityConformanceCheck.canon(r)); out.put(c, m); }
        return out;
    }

    private String compare(JsonNode want, Map<String, Object> got, Map<String, Map<String, String>> before, DocumentRepository repo) {
        if (got.containsKey("ret") || !want.get("ret").isNull()) {
            String a = AmenityConformanceCheck.canon(want.get("ret")), b = AmenityConformanceCheck.canon((JsonNode) got.get("ret"));
            // the JavaScript returns more (the whole report object): compare what Java returns
            JsonNode w = want.get("ret"), g = (JsonNode) got.get("ret");
            for (Iterator<String> it = g.fieldNames(); it.hasNext(); ) {
                String k = it.next();
                if (!AmenityConformanceCheck.canon(w.get(k)).equals(AmenityConformanceCheck.canon(g.get(k)))) return "returned " + k + "\n   want: " + AmenityConformanceCheck.canon(w.get(k)) + "\n   got:  " + AmenityConformanceCheck.canon(g.get(k));
            }
        }
        for (String c : TRACK) {
            List<String> gotNew = new ArrayList<>();
            Map<String, String> gotChanged = new LinkedHashMap<>();
            for (JsonNode r : repo.list("t", c)) {
                String id = r.get("id").asText();
                if (!before.get(c).containsKey(id)) { ObjectNode o = r.deepCopy(); o.remove("id"); gotNew.add(AmenityConformanceCheck.canon(o)); }
                else if (!before.get(c).get(id).equals(AmenityConformanceCheck.canon(r))) gotChanged.put(id, AmenityConformanceCheck.canon(r));
            }
            List<String> wantNew = new ArrayList<>();
            want.get("created").get(c).forEach(r -> wantNew.add(AmenityConformanceCheck.canon(r)));
            if (!wantNew.equals(gotNew)) return "new rows in " + c + "\n   want (" + wantNew.size() + "): " + wantNew + "\n   got  (" + gotNew.size() + "): " + gotNew;
            Map<String, String> wantChanged = new LinkedHashMap<>();
            want.get("changed").get(c).fields().forEachRemaining(e -> wantChanged.put(e.getKey(), AmenityConformanceCheck.canon(e.getValue())));
            if (!wantChanged.equals(gotChanged)) return "changed rows in " + c + "\n   want: " + wantChanged + "\n   got:  " + gotChanged;
        }
        return null;
    }
}
