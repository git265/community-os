import com.communityos.adapter.persistence.InMemoryDocumentRepository;
import com.communityos.port.DocumentRepository;
import com.communityos.security.Constants;
import com.communityos.security.Js;
import com.communityos.security.Principal;
import com.communityos.service.audit.AuditTrail;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.io.InputStream;
import java.time.Clock;
import java.time.Instant;
import java.time.LocalDate;
import java.time.ZoneId;
import java.time.ZoneOffset;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.zip.GZIPInputStream;

/**
 * Replays what the real JavaScript amenity code (src/lib/amenityServer.js) did for ~18,000 booking attempts and actions, and the ledger and credit
 * lines it posted afterwards (generated by backend/contract-server/test/gen-amenity-golden.mjs, `npm run gen:amenity`, run in the India time zone),
 * and reports every answer the Java rules give differently. Plain Java on purpose: runs under JUnit (AmenityConformanceTest) and from the command line.
 */
public final class AmenityConformanceCheck {
    public static final ZoneId ZONE = ZoneId.of("Asia/Kolkata");
    private final ObjectMapper json = new ObjectMapper();
    private final List<String> problems = new ArrayList<>();
    private int decisions, refused, postings;

    public static void main(String[] args) throws Exception {
        AmenityConformanceCheck c = new AmenityConformanceCheck();
        c.run();
        System.out.println("decisions=" + c.decisions + " refused=" + c.refused + " postings=" + c.postings + " mismatches=" + c.problems.size());
        c.problems.stream().limit(args.length > 0 ? Integer.parseInt(args[0]) : 12).forEach(System.out::println);
        System.exit(c.problems.isEmpty() ? 0 : 1);
    }

    List<String> problems() { return problems; }
    int decisions() { return decisions; }
    int refused() { return refused; }
    int postings() { return postings; }

    private static List<JsonNode> rows(JsonNode world, String c) { List<JsonNode> l = new ArrayList<>(); JsonNode a = world.get(c); if (a != null) a.forEach(l::add); return l; }

    void run() throws Exception {
        JsonNode gold;
        try (InputStream in = AmenityConformanceCheck.class.getResourceAsStream("/amenity/golden.json.gz")) {
            if (in == null) throw new IllegalStateException("amenity/golden.json.gz is missing: run `npm run gen:amenity` in backend/contract-server");
            gold = json.readTree(new GZIPInputStream(in));
        }
        Clock clock = Clock.fixed(Instant.parse("2026-10-19T12:00:00Z"), ZoneOffset.UTC);
        String localToday = LocalDate.now(clock.withZone(ZONE)).toString();
        Constants constants = Constants.load(json);
        for (JsonNode c : gold.get("cases")) {
            JsonNode world = c.get("world");
            List<JsonNode> settingsRows = rows(world, "amenitySettings"), financeRows = rows(world, "financeSettings");
            AmenityRules.Ctx ctx = new AmenityRules.Ctx(rows(world, "amenityTypes"), settingsRows.isEmpty() ? json.createObjectNode() : settingsRows.get(0), rows(world, "amenities"), rows(world, "unitCredits"),
                    rows(world, "properties"), rows(world, "amenityItems"));
            JsonNode finance = financeRows.isEmpty() ? json.createObjectNode() : financeRows.get(0);
            List<JsonNode> dues = rows(world, "dues");
            for (JsonNode pr : c.get("probes")) {
                JsonNode pj = pr.get("principal");
                Set<String> perms = new HashSet<>(); pj.get("role").get("permissions").forEach(x -> perms.add(x.asText()));
                Principal p = new Principal(pj.get("roleId").asText(), new Principal.Role(pj.get("roleId").asText(), pj.get("roleId").asText(), pj.get("role").get("category").asText(), perms),
                        pj.hasNonNull("name") ? pj.get("name").asText() : null, "", List.of());
                List<String[]> calls = new ArrayList<>();
                AmenityRules.PaymentVerifier verifier = (ref, unit, amount, bookingId) -> {
                    calls.add(new String[] {ref, unit, Js.numberToString(amount), bookingId});
                    if ("PAY-OK".equals(ref)) return "";
                    if ("PAY-USED".equals(ref)) return "That payment has already been used for another booking.";
                    if ("PAY-SMALL".equals(ref)) return amount > 500 ? "The payment is less than the booking total." : "";
                    if ("PAY-OTHER".equals(ref)) return "That payment was made for another unit.";
                    return "That payment was not found. Pay online first, then book.";
                };
                AmenityRules.DefaulterCheck defaulter = unit -> Defaulters.block(unit, finance, dues, localToday, ZONE);
                JsonNode record = pr.get("record");
                JsonNode old = pr.get("old") == null || pr.get("old").isNull() ? null : pr.get("old");
                boolean isNew = pr.get("isNew").asBoolean();
                String bookingId = Js.truthy(record, "id") ? Js.str(record, "id") : "";
                AmenityRules.Result got;
                String note = "";
                try { got = AmenityRules.preWrite(ctx, record, old, isNew, p, clock, ZONE, verifier, bookingId, defaulter, () -> AmenityRules.gatewayRef(clock)); }
                catch (RuntimeException e) { got = AmenityRules.Result.error("CRASH " + e); if (problems.isEmpty()) e.printStackTrace(); }
                JsonNode want = pr.get("expected");
                decisions++;
                if (!want.get("error").isNull()) refused++;
                String diff = compare(want, got);
                if (diff == null) diff = compareCalls(pr.get("calls"), calls);
                if (diff != null && problems.size() < 400) problems.add(diff + "\n   principal=" + pj.get("roleId").asText() + " isNew=" + isNew + "\n   record=" + record + "\n   old=" + old);
            }
            for (JsonNode post : c.get("posts")) {
                postings++;
                String diff = comparePost(world, post, clock, constants);
                if (diff != null && problems.size() < 400) problems.add(diff);
            }
        }
    }

    private String compare(JsonNode want, AmenityRules.Result got) {
        String wantErr = want.get("error").isNull() ? null : want.get("error").asText();
        if (wantErr != null || got.error() != null) {
            if (wantErr == null || !wantErr.equals(got.error())) return "error\n   want: " + wantErr + "\n   got:  " + got.error() + (got.error() == null ? "\n   record=" + got.record() : "");
            return null;
        }
        String wantAction = want.get("action").asText();
        if (!wantAction.equals(got.action())) return "action\n   want: " + wantAction + "\n   got:  " + got.action();
        String a = canon(want.get("record")), b = canon(got.record());
        if (!a.equals(b)) return "record\n   want: " + a + "\n   got:  " + b + "\n   differs: " + whatDiffers(want.get("record"), got.record());
        return null;
    }

    private String compareCalls(JsonNode want, List<String[]> got) {
        if (want.size() != got.size()) return "payment checks\n   want " + want.size() + " calls: " + want + "\n   got  " + got.size();
        for (int i = 0; i < got.size(); i++) {
            JsonNode w = want.get(i); String[] g = got.get(i);
            String wRef = w.hasNonNull("ref") ? Js.toStr(w.get("ref")) : "", wUnit = w.hasNonNull("unit") ? Js.toStr(w.get("unit")) : "", wId = w.hasNonNull("bookingId") ? Js.toStr(w.get("bookingId")) : "";
            if (!wRef.equals(g[0]) || !wUnit.equals(g[1]) || !wId.equals(g[3]) || Math.abs(w.get("amount").asDouble() - Double.parseDouble(g[2])) > 1e-9) return "payment check #" + i + "\n   want: " + w + "\n   got:  " + String.join(" | ", g);
        }
        return null;
    }

    private String comparePost(JsonNode world, JsonNode post, Clock clock, Constants constants) {
        DocumentRepository repo = new InMemoryDocumentRepository();
        for (String coll : List.of("amenitySettings", "bankAccounts", "ledger", "unitCredits")) for (JsonNode r : rows(world, coll)) repo.upsert("t", coll, r.get("id").asText(), r);
        Set<String> beforeLedger = new HashSet<>(), beforeCredits = new HashSet<>();
        repo.list("t", "ledger").forEach(r -> beforeLedger.add(r.get("id").asText()));
        repo.list("t", "unitCredits").forEach(r -> beforeCredits.add(r.get("id").asText()));
        AmenityPosting posting = new AmenityPosting(repo, new AuditTrail(repo, json, clock), json, clock, constants);
        try { posting.postWrite("t", post.get("next"), post.get("action").asText()); } catch (RuntimeException e) { e.printStackTrace(); return "posting crashed: " + e; }
        for (String coll : List.of("ledger", "unitCredits")) {
            Set<String> before = "ledger".equals(coll) ? beforeLedger : beforeCredits;
            List<String> got = new ArrayList<>(), want = new ArrayList<>();
            for (JsonNode r : repo.list("t", coll)) if (!before.contains(r.get("id").asText())) got.add(canon(withoutId(r)));
            post.get("expected").get(coll).forEach(r -> want.add(canon(r)));
            Collections.sort(got); Collections.sort(want);
            if (!got.equals(want)) return "posting " + post.get("action").asText() + " " + coll + "\n   want: " + want + "\n   got:  " + got + "\n   next=" + post.get("next");
        }
        return null;
    }

    private JsonNode withoutId(JsonNode r) { com.fasterxml.jackson.databind.node.ObjectNode o = r.deepCopy(); o.remove("id"); return o; }

    // ---- comparing two JSON values the way a person would: key order and 1 vs 1.0 do not matter, a generated gateway reference is masked --------------

    public static String canon(JsonNode n) {
        StringBuilder sb = new StringBuilder();
        canon(n, sb);
        return sb.toString();
    }
    private static void canon(JsonNode n, StringBuilder sb) {
        if (n == null || n.isMissingNode()) { sb.append("undefined"); return; }
        if (n.isNumber()) { sb.append(Js.numberToString(n.asDouble())); return; }
        if (n.isTextual()) { String s = n.asText(); sb.append('"').append(s.matches("^GW[0-9A-Z]{4,}$") ? "GW*" : s).append('"'); return; }
        if (n.isArray()) { sb.append('['); for (int i = 0; i < n.size(); i++) { if (i > 0) sb.append(','); canon(n.get(i), sb); } sb.append(']'); return; }
        if (n.isObject()) {
            Map<String, JsonNode> sorted = new TreeMap<>();
            for (Iterator<Map.Entry<String, JsonNode>> it = n.fields(); it.hasNext(); ) { Map.Entry<String, JsonNode> e = it.next(); sorted.put(e.getKey(), e.getValue()); }
            sb.append('{'); boolean first = true;
            for (Map.Entry<String, JsonNode> e : sorted.entrySet()) { if (!first) sb.append(','); first = false; sb.append(e.getKey()).append(':'); canon(e.getValue(), sb); }
            sb.append('}'); return;
        }
        sb.append(n.toString());
    }

    private static String whatDiffers(JsonNode want, JsonNode got) {
        Set<String> keys = new java.util.TreeSet<>();
        want.fieldNames().forEachRemaining(keys::add); got.fieldNames().forEachRemaining(keys::add);
        List<String> out = new ArrayList<>();
        for (String k : keys) if (!canon(want.get(k)).equals(canon(got.get(k)))) out.add(k + " want=" + canon(want.get(k)) + " got=" + canon(got.get(k)));
        return String.join("; ", out);
    }
}
