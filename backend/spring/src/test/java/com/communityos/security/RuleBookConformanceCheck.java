package com.communityos.security;

import com.communityos.domain.ScopeNode;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ArrayNode;
import com.fasterxml.jackson.databind.node.JsonNodeFactory;
import com.fasterxml.jackson.databind.node.ObjectNode;
import java.io.InputStream;
import java.time.Clock;
import java.time.Instant;
import java.time.ZoneOffset;
import java.util.ArrayList;
import java.util.Iterator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.zip.GZIPInputStream;

/**
 * Replays the decisions the real JavaScript rule book (src/lib/security/authz.js) gave for ~70,000 write questions and ~3,000 read
 * questions, and reports every place the Java rules answer differently. The corpus is generated by
 * backend/contract-server/test/gen-rulebook-golden.mjs (`npm run gen:rulebook`).
 *
 * Plain Java on purpose: runs under JUnit (RuleBookConformanceTest) and from the command line (`main`), no Spring needed.
 */
public final class RuleBookConformanceCheck {
    private final ObjectMapper json = new ObjectMapper();
    private final List<String> problems = new ArrayList<>();
    private int writes, reads;

    public static void main(String[] args) throws Exception {
        RuleBookConformanceCheck c = new RuleBookConformanceCheck();
        c.run();
        System.out.println("writes=" + c.writes + " reads=" + c.reads + " mismatches=" + c.problems.size());
        c.problems.stream().limit(args.length > 0 ? Integer.parseInt(args[0]) : 40).forEach(System.out::println);
        System.exit(c.problems.isEmpty() ? 0 : 1);
    }

    List<String> problems() { return problems; }
    int writes() { return writes; }
    int reads() { return reads; }

    void run() throws Exception {
        JsonNode gold;
        try (InputStream in = RuleBookConformanceCheck.class.getResourceAsStream("/rulebook/golden.json.gz")) {
            if (in == null) throw new IllegalStateException("golden.json.gz is missing: run `npm run gen:rulebook` in backend/contract-server");
            gold = json.readTree(new GZIPInputStream(in));
        }
        Constants constants = Constants.load(json);
        SchemaCatalog catalog = SchemaCatalog.defaults(json);
        Clock clock = Clock.fixed(Instant.parse(gold.get("clock").asText()), ZoneOffset.UTC);
        List<RuleContext> ctxs = new ArrayList<>();
        for (JsonNode v : gold.get("ctxVariants")) ctxs.add(RuleContext.defaults(constants).withApprovers(strings(v.get("second")), v.get("ecFinal").asBoolean()).withClock(clock));

        List<Principal> principals = new ArrayList<>();
        for (JsonNode p : gold.get("principals")) {
            String roleId = p.get("roleId").asText();
            principals.add(new Principal(roleId, catalog.role(roleId), p.get("name").asText(), p.get("unit").asText(), strings(p.get("blocks")), List.of(), "la-paloma", "u-" + roleId, "", ""));
        }
        JsonNode fixtures = gold.get("fixtures");
        RawReader raw = (collection) -> { List<JsonNode> out = new ArrayList<>(); JsonNode rows = fixtures.get(collection); if (rows != null) rows.forEach(out::add); return out; };
        WriteRules rules = new WriteRules(constants);

        for (JsonNode t : gold.get("writes")) {
            writes++;
            Principal p = principals.get(t.get(0).asInt());
            String collection = t.get(1).asText();
            RuleContext ctx = ctxs.get(t.get(2).asInt());
            String op = t.get(3).asText();
            int rowIdx = t.get(4).asInt();
            JsonNode rows = fixtures.get(collection);
            JsonNode old = rowIdx < 0 || op.equals("create") ? null : rows.get(rowIdx).deepCopy();
            JsonNode next;
            if (op.equals("create")) { ObjectNode n = rows != null && rows.size() > 0 ? rows.get(0).deepCopy() : json.createObjectNode().put("id", "new"); n.put("id", "new-1"); n.remove("shortId"); n.remove("recVersion"); next = n; }
            else next = old == null ? json.createObjectNode() : old.deepCopy();
            if (!t.get(5).isNull()) ((ObjectNode) next).set(t.get(5).asText(), json.readTree(t.get(6).asText()));
            Verdict v = rules.authorize(new WriteCall(collection, p, catalog.schema(collection), old, next, op, ctx));
            boolean wantOk = t.get(7).asInt() == 1;
            String wantReason = wantOk ? null : t.get(8).asText();
            if (v.ok() != wantOk || (!wantOk && !wantReason.equals(v.reason()))) {
                problems.add("WRITE " + collection + " " + op + " as " + p.roleId() + "/" + p.name() + " row=" + rowIdx + " key=" + t.get(5).asText() + " value=" + t.get(6).asText()
                        + "\n    js  : " + (wantOk ? "OK" : wantReason) + "\n    java: " + (v.ok() ? "OK" : v.reason()));
            }
            boolean bo = BlockScope.writeOk(collection, op.equals("delete") ? old : next, old, p, raw);
            if (bo != (t.get(9).asInt() == 1)) problems.add("BLOCK " + collection + " " + op + " as " + p.roleId() + " row=" + rowIdx + " js=" + t.get(9).asInt() + " java=" + bo);
        }

        RuleContext readCtx = ctxs.get(0);
        for (JsonNode t : gold.get("reads")) {
            reads++;
            Principal p = principals.get(t.get(0).asInt());
            String collection = t.get(1).asText();
            String who = collection + " as " + p.roleId() + "/" + p.name() + (p.blocks().isEmpty() ? "" : " blocks=" + p.blocks());
            if (ReadRules.canRead(collection, p) != (t.get(2).asInt() == 1)) problems.add("CANREAD " + who);
            if (rules.canWriteCollection(collection, p) != (t.get(3).asInt() == 1)) problems.add("CANWRITE " + who);
            Schema schema = catalog.schema(collection);
            List<String> hidden = FieldMasking.hiddenFieldKeys(schema, p.roleId(), p);
            if (!hidden.equals(strings(t.get(4)))) problems.add("HIDDEN " + who + "\n    js  : " + t.get(4) + "\n    java: " + hidden);
            RowScope scope = RowScopes.rowScope(collection, p, raw, readCtx);
            String wantSql = t.get(5).isInt() ? null : t.get(5).asText();
            String gotSql = scope.sql() == null ? null : canon(scope.sql().toJson());
            if (!java.util.Objects.equals(wantSql, gotSql)) problems.add("SQL " + who + "\n    js  : " + wantSql + "\n    java: " + gotSql);
            if ((scope.predicate() != null) != (t.get(6).asInt() == 1)) problems.add("PREDICATE " + who + " js=" + t.get(6).asInt());
            ArrayNode kept = JsonNodeFactory.instance.arrayNode();
            for (JsonNode r : raw.read(collection)) {
                if (scope.predicate() != null && !scope.predicate().test(r)) continue;
                JsonNode x = scope.transform() != null ? scope.transform().apply(r) : r;
                kept.add(FieldMasking.mask(x, schema, p.roleId(), p));
            }
            String gotRows = canon(kept);
            if (!gotRows.equals(t.get(7).asText())) problems.add("ROWS " + who + "\n    js  : " + trim(t.get(7).asText()) + "\n    java: " + trim(gotRows));
        }
    }

    private static String trim(String s) { return s.length() > 600 ? s.substring(0, 600) + "…" : s; }
    private static List<String> strings(JsonNode a) { List<String> out = new ArrayList<>(); a.forEach((x) -> out.add(x.asText())); return out; }

    /** Same canonical form as the generator's canon(): object keys sorted at every level, JavaScript number formatting. */
    static String canon(JsonNode n) { return Js.stringify(sorted(n)); }
    private static JsonNode sorted(JsonNode n) {
        if (n.isObject()) {
            Map<String, JsonNode> m = new TreeMap<>();
            for (Iterator<Map.Entry<String, JsonNode>> it = n.fields(); it.hasNext(); ) { Map.Entry<String, JsonNode> e = it.next(); m.put(e.getKey(), sorted(e.getValue())); }
            ObjectNode o = JsonNodeFactory.instance.objectNode();
            m.forEach(o::set);
            return o;
        }
        if (n.isArray()) { ArrayNode a = JsonNodeFactory.instance.arrayNode(); n.forEach((x) -> a.add(sorted(x))); return a; }
        return n;
    }
}
